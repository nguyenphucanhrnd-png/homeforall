import { existsSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { JOURNEY, JOURNEY_TRACK, LANDING_TRACK, PLATE_IDS, PLATES, ROUTES } from "./world.config";

const APP = join(process.cwd(), "src/app/[locale]");
const pageExists = (href: string) => {
  const path = href.split(/[?#]/)[0].replace(/^\//, "");
  return existsSync(join(APP, path, "page.tsx"));
};

describe("world.config", () => {
  it("has six journey steps numbered 1–6 with unique hashes", () => {
    expect(JOURNEY.map((s) => s.n)).toEqual([1, 2, 3, 4, 5, 6]);
    expect(new Set(JOURNEY.map((s) => s.hash)).size).toBe(6);
  });

  it("every step's 'go to the feature' link points at a real page (scene promises, feature delivers)", () => {
    for (const step of JOURNEY) expect(pageExists(step.feature.href), step.feature.href).toBe(true);
  });

  it("every configured route exists as a page", () => {
    for (const route of Object.keys(ROUTES)) {
      expect(pageExists(route.replace("[code]", "[code]")), route).toBe(true);
    }
  });

  it("journey plate ranges cover 0 → 1 without gaps or overlaps", () => {
    expect(JOURNEY_TRACK[0].from).toBe(0);
    expect(JOURNEY_TRACK.at(-1)!.to).toBe(1);
    for (let i = 1; i < JOURNEY_TRACK.length; i++) {
      expect(JOURNEY_TRACK[i].from).toBeCloseTo(JOURNEY_TRACK[i - 1].to, 10);
    }
  });

  it("each journey step's plates appear in the pinned track in order", () => {
    const order = JOURNEY_TRACK.map((s) => s.plate);
    expect(JOURNEY.flatMap((s) => s.plates)).toEqual(order);
  });

  it("references only known plates, with fallbacks that do not loop", () => {
    const ids = new Set<string>(PLATE_IDS);
    for (const seg of LANDING_TRACK) if (seg.plate) expect(ids.has(seg.plate)).toBe(true);
    for (const id of PLATE_IDS) {
      const seen = new Set<string>([id]);
      let fb = PLATES[id].fallback;
      while (fb) {
        expect(seen.has(fb.plate), `fallback loop at ${id}`).toBe(false);
        seen.add(fb.plate);
        fb = PLATES[fb.plate].fallback;
      }
    }
  });

  it("captions exist in both languages (canvas aria-label + still alt)", () => {
    for (const id of PLATE_IDS) {
      expect(PLATES[id].caption.vi.length).toBeGreaterThan(10);
      expect(PLATES[id].caption.en.length).toBeGreaterThan(10);
    }
  });
});

